-- R06: domiciliarios y su disponibilidad.
CREATE TABLE domiciliario (
    id_domiciliario       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre                VARCHAR(120) NOT NULL,
    telefono              VARCHAR(120) NOT NULL,
    estado_disponibilidad VARCHAR(120) NOT NULL DEFAULT 'disponible',
    CONSTRAINT pk_domiciliario          PRIMARY KEY (id_domiciliario),
    CONSTRAINT uq_domiciliario_telefono UNIQUE (telefono),
    CONSTRAINT ck_domiciliario_disponibilidad CHECK (estado_disponibilidad IN
        ('disponible','ocupado','desconectado'))
);
