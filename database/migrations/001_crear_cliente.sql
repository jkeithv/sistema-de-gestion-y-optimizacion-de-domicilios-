-- R01: datos basicos para identificar y contactar al cliente.
CREATE TABLE cliente (
    id_cliente  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(120) NOT NULL,
    telefono    VARCHAR(120) NOT NULL,
    correo      VARCHAR(120),
    CONSTRAINT pk_cliente        PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_correo UNIQUE (correo),
    CONSTRAINT ck_cliente_nombre CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_cliente_correo CHECK (correo IS NULL OR correo LIKE '%_@_%')
);
