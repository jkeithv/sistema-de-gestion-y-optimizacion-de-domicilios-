-- R03: pedido realizado por un cliente hacia una de sus direcciones.
CREATE TABLE pedido (
    id_pedido      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente     INTEGER NOT NULL,
    id_direccion   INTEGER NOT NULL,
    fecha_hora     TIMESTAMP NOT NULL DEFAULT now(),
    estado_pedido  VARCHAR(120) NOT NULL DEFAULT 'pendiente',
    observaciones  VARCHAR(120),
    CONSTRAINT pk_pedido PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_direccion FOREIGN KEY (id_direccion)
        REFERENCES direccion (id_direccion) ON DELETE RESTRICT,
    -- La direccion elegida debe ser del mismo cliente que hace el pedido.
    CONSTRAINT fk_pedido_direccion_cliente FOREIGN KEY (id_direccion, id_cliente)
        REFERENCES direccion (id_direccion, id_cliente) ON DELETE RESTRICT,
    CONSTRAINT ck_pedido_estado CHECK (estado_pedido IN
        ('pendiente','asignado','en_camino','entregado','cancelado'))
);
