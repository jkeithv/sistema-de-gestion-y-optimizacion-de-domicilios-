-- R05: empleados que gestionan pedidos y servicios en una central.
CREATE TABLE empleado_central (
    id_empleado  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_central   INTEGER NOT NULL,
    nombre       VARCHAR(120) NOT NULL,
    telefono     VARCHAR(120),
    correo       VARCHAR(120),
    cargo        VARCHAR(120),
    CONSTRAINT pk_empleado_central PRIMARY KEY (id_empleado),
    CONSTRAINT fk_empleado_central FOREIGN KEY (id_central)
        REFERENCES central (id_central) ON DELETE RESTRICT,
    CONSTRAINT uq_empleado_correo UNIQUE (correo)
);
