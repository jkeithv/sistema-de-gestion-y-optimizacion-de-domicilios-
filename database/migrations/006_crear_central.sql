-- R05: central que organiza los servicios.
CREATE TABLE central (
    id_central  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(120) NOT NULL,
    telefono    VARCHAR(120),
    direccion   VARCHAR(120),
    CONSTRAINT pk_central        PRIMARY KEY (id_central),
    CONSTRAINT uq_central_nombre UNIQUE (nombre)
);
