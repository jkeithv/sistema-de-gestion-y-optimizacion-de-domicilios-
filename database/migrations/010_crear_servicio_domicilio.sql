-- 010_crear_servicio_domicilio.sql
-- R08, R13: operacion logistica de entrega. Un pedido genera un unico servicio.
CREATE TABLE servicio_domicilio (
    id_servicio       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_pedido         INTEGER NOT NULL,
    id_empleado       INTEGER NOT NULL,
    id_domiciliario   INTEGER NOT NULL,
    fecha_asignacion  TIMESTAMP NOT NULL DEFAULT now(),
    fecha_recogida    TIMESTAMP,
    fecha_entrega     TIMESTAMP,
    estado_servicio   VARCHAR(120) NOT NULL DEFAULT 'asignado',
    CONSTRAINT pk_servicio_domicilio PRIMARY KEY (id_servicio),
    CONSTRAINT uq_servicio_pedido UNIQUE (id_pedido),
    CONSTRAINT fk_servicio_pedido FOREIGN KEY (id_pedido)
        REFERENCES pedido (id_pedido) ON DELETE RESTRICT,
    CONSTRAINT fk_servicio_empleado FOREIGN KEY (id_empleado)
        REFERENCES empleado_central (id_empleado) ON DELETE RESTRICT,
    CONSTRAINT fk_servicio_domiciliario FOREIGN KEY (id_domiciliario)
        REFERENCES domiciliario (id_domiciliario) ON DELETE RESTRICT,
    CONSTRAINT ck_servicio_estado CHECK (estado_servicio IN
        ('asignado','recogido','en_camino','entregado','cancelado')),
    -- Rangos de fechas coherentes (si alguna es NULL, la regla no aplica).
    CONSTRAINT ck_servicio_recogida CHECK (fecha_recogida IS NULL OR fecha_recogida >= fecha_asignacion),
    CONSTRAINT ck_servicio_entrega  CHECK (fecha_entrega  IS NULL OR fecha_entrega  >= COALESCE(fecha_recogida, fecha_asignacion)),
    -- Un servicio entregado debe tener fecha de entrega.
    CONSTRAINT ck_servicio_entregado_fecha CHECK (estado_servicio <> 'entregado' OR fecha_entrega IS NOT NULL)
);
