-- R10: rutas propuestas o utilizadas para un servicio.
CREATE TABLE ruta (
    id_ruta             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_servicio         INTEGER NOT NULL,
    fecha_hora_consulta TIMESTAMP NOT NULL DEFAULT now(),
    origen_latitud      DECIMAL(9,6) NOT NULL,
    origen_longitud     DECIMAL(9,6) NOT NULL,
    destino_latitud     DECIMAL(9,6) NOT NULL,
    destino_longitud    DECIMAL(9,6) NOT NULL,
    distancia_km        DECIMAL(12,2),
    tiempo_estimado_min INTEGER,
    condicion_trafico   VARCHAR(120),
    CONSTRAINT pk_ruta PRIMARY KEY (id_ruta),
    CONSTRAINT fk_ruta_servicio FOREIGN KEY (id_servicio)
        REFERENCES servicio_domicilio (id_servicio) ON DELETE CASCADE,
    CONSTRAINT ck_ruta_origen_lat  CHECK (origen_latitud   BETWEEN -90  AND 90),
    CONSTRAINT ck_ruta_origen_lon  CHECK (origen_longitud  BETWEEN -180 AND 180),
    CONSTRAINT ck_ruta_destino_lat CHECK (destino_latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_ruta_destino_lon CHECK (destino_longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_ruta_distancia   CHECK (distancia_km IS NULL OR distancia_km >= 0),
    CONSTRAINT ck_ruta_tiempo      CHECK (tiempo_estimado_min IS NULL OR tiempo_estimado_min >= 0),
    CONSTRAINT ck_ruta_trafico     CHECK (condicion_trafico IS NULL OR condicion_trafico IN
        ('fluido','moderado','congestionado'))
);
