-- 002_crear_direccion.sql
-- R02: un cliente puede tener varias direcciones.
CREATE TABLE direccion (
    id_direccion  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    INTEGER NOT NULL,
    direccion     VARCHAR(120) NOT NULL,
    barrio        VARCHAR(120),
    ciudad        VARCHAR(120) NOT NULL DEFAULT 'Valledupar',
    latitud       DECIMAL(9,6),
    longitud      DECIMAL(9,6),
    CONSTRAINT pk_direccion PRIMARY KEY (id_direccion),
    CONSTRAINT fk_direccion_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    -- Permite que PEDIDO verifique que la direccion pertenece al mismo cliente.
    CONSTRAINT uq_direccion_id_cliente UNIQUE (id_direccion, id_cliente),
    CONSTRAINT ck_direccion_latitud  CHECK (latitud  IS NULL OR latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_direccion_longitud CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180)
);
