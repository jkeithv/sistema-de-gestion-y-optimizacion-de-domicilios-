-- R07: vehiculo asociado al domiciliario.
CREATE TABLE vehiculo (
    id_vehiculo      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_domiciliario  INTEGER NOT NULL,
    tipo             VARCHAR(120) NOT NULL,
    placa            VARCHAR(120) NOT NULL,
    estado           VARCHAR(120) NOT NULL DEFAULT 'activo',
    CONSTRAINT pk_vehiculo PRIMARY KEY (id_vehiculo),
    CONSTRAINT fk_vehiculo_domiciliario FOREIGN KEY (id_domiciliario)
        REFERENCES domiciliario (id_domiciliario) ON DELETE RESTRICT,
    CONSTRAINT uq_vehiculo_placa UNIQUE (placa),
    CONSTRAINT ck_vehiculo_tipo   CHECK (tipo   IN ('moto','bicicleta','carro')),
    CONSTRAINT ck_vehiculo_estado CHECK (estado IN ('activo','mantenimiento','inactivo'))
);
