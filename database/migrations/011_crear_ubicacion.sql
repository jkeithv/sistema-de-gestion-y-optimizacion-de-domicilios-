-- R09: historial de posiciones del domiciliario durante un servicio.
CREATE TABLE ubicacion (
    id_ubicacion     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_domiciliario  INTEGER NOT NULL,
    id_servicio      INTEGER NOT NULL,
    fecha_hora       TIMESTAMP NOT NULL DEFAULT now(),
    latitud          DECIMAL(9,6) NOT NULL,
    longitud         DECIMAL(9,6) NOT NULL,
    CONSTRAINT pk_ubicacion PRIMARY KEY (id_ubicacion),
    CONSTRAINT fk_ubicacion_domiciliario FOREIGN KEY (id_domiciliario)
        REFERENCES domiciliario (id_domiciliario) ON DELETE RESTRICT,
    CONSTRAINT fk_ubicacion_servicio FOREIGN KEY (id_servicio)
        REFERENCES servicio_domicilio (id_servicio) ON DELETE CASCADE,
    CONSTRAINT ck_ubicacion_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_ubicacion_longitud CHECK (longitud BETWEEN -180 AND 180)
);
